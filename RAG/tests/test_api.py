def test_query_rag_success(client, mock_pipeline):
    """Test POST /api/v1/query with a valid payload."""
    payload = {
        "query": "What is ADMT under Section 7001?",
        "tags": ["unit-test"],
        "metadata": {"user_id": "test_user_123"}
    }
    response = client.post("/api/v1/query", json=payload)
    
    assert response.status_code == 200
    data = response.json()
    
    # Validate structure and values against QueryResponse schema
    assert data["query"] == "What is ADMT under Section 7001?"
    assert "Automated Decisionmaking Technology" in data["answer"]
    assert data["route"] == "POLICY_LOOKUP"
    assert data["route_reasoning"] == "Query requests specific statutory definition."
    assert data["abstained"] is False
    assert data["citation_valid"] is True
    assert len(data["sources"]) == 1
    assert "execution_time_sec" in data

    # Verify pipeline was called with correct arguments
    mock_pipeline.query.assert_called_once_with(
        user_query="What is ADMT under Section 7001?",
        tags=["unit-test"],
        metadata={"user_id": "test_user_123"}
    )


def test_query_rag_validation_error(client):
    """Test POST /api/v1/query with invalid query string (shorter than min_length=3)."""
    payload = {"query": "ab"}
    response = client.post("/api/v1/query", json=payload)
    
    # 422 Unprocessable Entity generated by Pydantic QueryRequest schema
    assert response.status_code == 422


def test_query_rag_missing_body(client):
    """Test POST /api/v1/query with empty JSON payload."""
    response = client.post("/api/v1/query", json={})
    assert response.status_code == 422


def test_query_rag_internal_exception(client, mock_pipeline):
    """Test POST /api/v1/query exception handling when pipeline fails."""
    mock_pipeline.query.side_effect = Exception("ChromaDB connection timeout")

    payload = {"query": "What are dark patterns?"}
    response = client.post("/api/v1/query", json=payload)
    
    assert response.status_code == 500
    assert "RAG execution error: ChromaDB connection timeout" in response.json()["detail"]